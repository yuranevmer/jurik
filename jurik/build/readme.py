_LIMITS = """\
## Обмеження

- Правки однієї редакції з кількома підставами не розділяються між законами.
- Якщо на zakon немає окремої редакції для закону (подія є в історії картки, редакції
  немає), його правки потрапляють у коміт наступної редакції під її підставою.
- Законопроекти до кодексів знайдено за назвою; «комплексні» законопроекти («до деяких
  законодавчих актів»), що не називають кодекс, не враховано.
- Тексти законопроектів у форматі Word 97 (`.doc`) не конвертуються.
"""


def _codes_table(codes: Iterable[Code]) -> str:
    rows = ["## Кодекси", "", "| Папка | Назва | Документ zakon |", "|---|---|---|"]
    for code in codes:
        ids = ", ".join(f"[{i}]({ZAKON_URL.format(i)})" for i in code.zakon_ids)
        title = code.title
        if code.repealed:
            title += f" (втратив чинність {code.repealed:%d.%m.%Y})"
        rows.append(f"| `codes/{code.slug}` | {title} | {ids} |")
    return "\n".join(rows) + "\n"


def _limits(bills_limit: int | None) -> str:
    text = _LIMITS
    if bills_limit is not None:
        text += (
            f"- У цій збірці гілок законопроектів без злиття не більше {bills_limit} "
            "(найраніше зареєстровані); решта не включена.\n"
        )
    return text


def readme_markdown(codes: Sequence[Code], *, bills_limit: int | None = None) -> str:
    """``README.md`` of the laws repository built from ``codes``; ``bills_limit`` = the cap
    on branches of bills that did not become law (``jurik build --bills-limit``)."""
    parts = [_INTRO, _codes_table(codes), _LAYOUT, _HISTORY, _USAGE, _limits(bills_limit)]
    return "\n".join(parts)


def add_readme(steps: list[Step], codes: Sequence[Code], *, bills_limit: int | None = None) -> None:
    """Put ``README.md`` into the change set of the first commit of ``main`` (no-op when the
    plan is empty)."""
    first = next((s for s in steps if s.ref == MAIN), None)
    if first is not None:
        content = readme_markdown(codes, bills_limit=bills_limit)
        first.changes.modified[README_PATH] = content.encode("utf-8")
